# -*- coding: utf-8 -*-
# Paso 08 · Sitio publico con los resultados de Angel, en Rpipe/docs/ (GitHub Pages,
# https://makijota.github.io/Arg_crecimiento/). Solo va al repo Arg_crecimiento.
# Los calculos, graficos, mapas y textos son los de lib/resultados.R, los mismos que usa
# el reporte (06_reporte.R); aca solo se arman las paginas de Jekyll (tema Just the Docs).
#
# Salida (todo generado, se pisa en cada corrida):
#   docs/_config.yml, docs/index.md, docs/method.md, docs/argentina.md,
#   docs/agglomerations/index.md, docs/agglomerations/<slug>.md, docs/assets/img/
#
# Uso: Rscript Rpipe/scripts/08_sitio.R [--sin-mapas]

script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
SCRIPTS <- normalizePath(dirname(script), winslash = "/")
RPIPE <- dirname(SCRIPTS)
source(file.path(SCRIPTS, "lib", "cajas.R"))
source(file.path(SCRIPTS, "lib", "resultados.R"))
SIN_MAPAS <- "--sin-mapas" %in% commandArgs(trailingOnly = TRUE)

DOCS <- file.path(RPIPE, "docs")
IMG <- file.path(DOCS, "assets", "img")
REPO <- "https://github.com/MakiJota/Arg_crecimiento"
dir.create(file.path(DOCS, "agglomerations"), recursive = TRUE, showWarnings = FALSE)

r <- cargar_resultados(RPIPE)
graficos(r, IMG)
if (!SIN_MAPAS) mapas(r, IMG)

url <- function(p) sprintf("{{ '%s' | relative_url }}", p)
img <- function(ruta, alt) sprintf("![%s](%s)", alt, url(paste0("/assets/img/", ruta)))
enlace <- function(s) sprintf("[%s](%s)", r$fichas$nombre[r$fichas$slug == s], url(sprintf("/agglomerations/%s/", s)))
mapas_html <- function(s) c(
  '<div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(300px,1fr));gap:10px">',
  vapply(ANIOS, function(a) {
    u <- url(sprintf("/assets/img/maps/%s_%d.png", s, a))
    sprintf('<a href="%s"><img src="%s" alt="%s %d" loading="lazy" style="width:100%%"></a>', u, u,
            r$fichas$nombre[r$fichas$slug == s], a)
  }, ""),
  "</div>", "", "Click a map for full size.")
escribir <- function(lineas, ...) writeLines(enc2utf8(lineas), file.path(DOCS, ...), useBytes = TRUE)
encabezado <- function(titulo, orden, extra = character())
  c("---", sprintf('title: "%s"', titulo), sprintf("nav_order: %d", orden), extra, "---", "")
toc <- c("1. TOC", "{:toc}", "")

escribir(c(
  "title: Urban growth in Argentina's agglomerations",
  sprintf("description: Angel / Atlas of Urban Expansion classes on GISD30, %d agglomerations, 1990-2020", r$n),
  "remote_theme: just-the-docs/just-the-docs@v0.10.1",
  "plugins:", "  - jekyll-remote-theme",
  'baseurl: "/Arg_crecimiento"',
  "permalink: pretty",
  "search_enabled: true",
  "aux_links:", sprintf('  "Code on GitHub": "%s"', REPO),
  sprintf('footer_content: "Exploratory results. Generated by <code>scripts/08_sitio.R</code> from GISD30 (Zhang et al. 2022, CC BY 4.0) on %s."',
          format(Sys.Date()))), "_config.yml")

escribir(c(encabezado("Home", 1),
  "# Urban growth in Argentina's agglomerations, 1990-2020", "",
  sprintf("How the %d EPH urban agglomerations of Argentina grew between 1990 and 2020, measured with the classes of the **Atlas of Urban Expansion** (Angel et al. 2016) on the **GISD30** impervious-surface record (Landsat, 30 m).", r$n), "",
  "The question behind every page: **how much does it change the picture to count the fringe open space** (the 100 m ring of unbuilt land around urban and suburban built-up) as part of the city?", "",
  "## In one paragraph", "", resumen_md(r), "",
  "## Pages", "",
  sprintf("- [Method](%s): data, classes, how \"the city\" is chosen, metrics, caveats.", url("/method/")),
  sprintf("- [Argentina](%s): totals and the comparison of all %d agglomerations.", url("/argentina/"), r$n),
  sprintf("- [Agglomerations](%s): one page each, with its growth charts and four maps.", url("/agglomerations/")), "",
  "## Status", "",
  "Exploratory. These numbers are not figures of the *Bolsones de pobreza* consultancy (IDB) and are not in its canonical figures file. Every number on this site is recomputed from the pipeline outputs; none is typed by hand.", "",
  sprintf("Code: [%s](%s).", REPO, REPO)), "index.md")

escribir(c(encabezado("Method", 2), "# Method", "", toc, metodo_md(r), "",
  "## Pipeline", "",
  tabla(c("Step", "Script", "What it does"), list(
    c("00", "`00_gisd30_descarga.R`", "GISD30 tiles for Argentina (Zenodo, md5 checked)"),
    c("01", "`01_gisd30_decadas.R`", "eight five-year epochs to four cumulative decades"),
    c("02", "`02_landsat_bbox.R`", "Landsat composite of each box (grid template for 04)"),
    c("03", "`03_ghsl_built_s.R`", "GHSL built-up surface, to compare with GISD30"),
    c("04", "`04_angel_atlas.R`", "Angel classes and metrics per decade"),
    c("04b", "`04b_angel_sin_landsat.R`", "the same as 04, cutting GISD30 with the box instead of the Landsat grid (no step 02 needed)"),
    c("05", "`05_per_muni.R`", "runs 02 + 04 for a list of agglomerations from `cajas.md`"),
    c("06", "`06_reporte.R`", "the same results as one markdown report"),
    c("07", "`07_limites_aglomerados.R`", "agglomerate perimeters and boxes to a GeoPackage"),
    c("08", "`08_sitio.R`", "this site"))), "",
  "## References", "",
  "- Angel, S. et al. (2016). *Atlas of Urban Expansion, 2016 Edition. Volume 1: Areas and Densities.* NYU, UN-Habitat, Lincoln Institute of Land Policy.",
  "- Angel, S., Parent, J. & Civco, D. (2007). Urban sprawl metrics: an analysis of global urban expansion using GIS. ASPRS Annual Conference.",
  "- Zhang, X. et al. (2022). GISD30: global 30 m impervious-surface dynamic dataset from 1985 to 2020 using time-series Landsat imagery on the Google Earth Engine platform. *Earth System Science Data* 14, 1831-1856."),
  "method.md")

escribir(c(encabezado("Argentina", 3), "# Argentina: all agglomerations together", "", toc,
           argentina_md(r, img, enlace)), "argentina.md")

escribir(c(encabezado("Agglomerations", 4, "has_children: true"), "# Agglomerations", "",
  sprintf("One page for each of the %d agglomerations: how it grew by Angel class, the effect of counting the fringe, and maps for 1990, 2000, 2010 and 2020.", r$n), "",
  tabla(c("Agglomeration", "Province", "extent 2020 (km²)", "built-up growth (% / yr)", "pace", "shape"),
        lapply(seq_len(nrow(r$fichas)), function(i) with(r$fichas[i, ], c(enlace(slug), provincia, f1(extension_2020),
                                                                         f2(t_construido), as.character(ritmo), forma))))),
  "agglomerations", "index.md")

for (i in seq_len(nrow(r$fichas))) {
  s <- r$fichas$slug[i]
  escribir(c(encabezado(r$fichas$nombre[i], i, "parent: Agglomerations"), sprintf("# %s", r$fichas$nombre[i]), "",
             aglomerado_md(r, s, img, mapas_html)), "agglomerations", sprintf("%s.md", s))
}
# paginas de aglomerados que ya no estan (por si cambia la lista)
viejas <- setdiff(sub("\\.md$", "", list.files(file.path(DOCS, "agglomerations"), "\\.md$")), c("index", r$fichas$slug))
unlink(file.path(DOCS, "agglomerations", paste0(viejas, ".md")))

cat(sprintf("Sitio escrito en %s: %d aglomerados\n", DOCS, r$n))
