# -*- coding: utf-8 -*-
# Paso 06 · Reporte de las metricas de Angel para los aglomerados, en un solo markdown.
# Reemplaza al reporte de 13 ciudades escrito a mano (outputs/reports/REPORTE_angel.md):
# este se genera entero desde resumen.csv con lib/resultados.R, igual que el sitio
# (08_sitio.R), asi que ningun numero se escribe a mano.
#
# Salida, pensada para leerse en GitHub o en la vista previa de VS Code:
#   reporte/REPORTE_angel.md
#   reporte/img/argentina_*.png, reporte/img/agl/<slug>_*.png, reporte/img/maps/<slug>_<anio>.png
# Las imagenes van con rutas relativas al .md: se mueve la carpeta reporte/ entera.
#
# Uso: Rscript Rpipe/scripts/06_reporte.R [--sin-mapas]

script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
SCRIPTS <- normalizePath(dirname(script), winslash = "/")
RPIPE <- dirname(SCRIPTS)
source(file.path(SCRIPTS, "lib", "cajas.R"))
source(file.path(SCRIPTS, "lib", "resultados.R"))
SIN_MAPAS <- "--sin-mapas" %in% commandArgs(trailingOnly = TRUE)

SAL <- file.path(RPIPE, "reporte")
IMG <- file.path(SAL, "img")
dir.create(IMG, recursive = TRUE, showWarnings = FALSE)

r <- cargar_resultados(RPIPE)
graficos(r, IMG)
if (!SIN_MAPAS) mapas(r, IMG)

# ancla de un encabezado como la arma GitHub: minusculas, sin puntuacion, espacios a guion
ancla <- function(x) gsub(" ", "-", gsub("[^\\p{L}\\p{N} _-]", "", tolower(x), perl = TRUE))
img <- function(ruta, alt) sprintf("![%s](img/%s)", alt, ruta)
enlace <- function(s) {
  nm <- r$fichas$nombre[r$fichas$slug == s]
  sprintf("[%s](#%s)", nm, ancla(nm))
}
mapas_html <- function(s) {
  celda <- function(a) sprintf('<td><a href="img/maps/%s_%d.png"><img src="img/maps/%s_%d.png" width="420" alt="%d"></a></td>',
                               s, a, s, a, a)
  c("<table>", paste0("<tr>", celda(1990), celda(2000), "</tr>"),
    paste0("<tr>", celda(2010), celda(2020), "</tr>"), "</table>")
}

L <- c(
  sprintf("# Angel / Atlas 2016 metrics on GISD30 · %d Argentine agglomerations, 1990-2020", r$n), "",
  sprintf("Exploratory. None of these numbers are project figures (they are not in `CIFRAS_CANONICAS.json`). The whole report, every number and every label included, is generated by `Rpipe/scripts/06_reporte.R` from `Rpipe/outputs/angel/resumen.csv` (step 04). Run of %s.", format(Sys.Date())), "",
  "**Question:** how is each agglomeration growing, and how much does it change the picture to count the *fringe open space* (the 100 m ring of unbuilt land around urban and suburban built-up) as part of the city?", "",
  "## Contents", "",
  "1. [Summary](#summary)", "2. [Method](#method)", "3. [Argentina](#argentina)",
  sprintf("4. [Agglomerations](#agglomerations): %s", paste(vapply(r$fichas$slug, enlace, ""), collapse = " · ")), "",
  "## Summary", "", resumen_md(r), "",
  "## Method", "", metodo_md(r, h = "###"), "",
  "### Pipeline (`Rpipe/scripts/`)", "",
  tabla(c("Step", "Script", "What it does"), list(
    c("00", "`00_gisd30_descarga.R`", "GISD30 tiles for Argentina (Zenodo, md5 checked)"),
    c("01", "`01_gisd30_decadas.R`", "eight five-year epochs to four cumulative decades"),
    c("02", "`02_landsat_bbox.R`", "Landsat composite of each box (grid template for 04)"),
    c("03", "`03_ghsl_built_s.R`", "GHSL built-up surface, to compare with GISD30"),
    c("04", "`04_angel_atlas.R`", "Angel classes and metrics per decade"),
    c("04b", "`04b_angel_sin_landsat.R`", "the same as 04, cutting GISD30 with the box instead of the Landsat grid (no step 02 needed)"),
    c("05", "`05_per_muni.R`", "runs 02 + 04 for a list of agglomerations from `Rpipe/cajas.md`"),
    c("06", "`06_reporte.R`", "this report"),
    c("07", "`07_limites_aglomerados.R`", "agglomerate perimeters and boxes to `Rpipe/raw/boundaries/aglomerados.gpkg`"))), "",
  "## Argentina", "", argentina_md(r, img, enlace, h = "###"), "",
  "## Agglomerations", "")
for (s in r$fichas$slug) {
  L <- c(L, sprintf("### %s", r$fichas$nombre[r$fichas$slug == s]), "",
         aglomerado_md(r, s, img, mapas_html, h = "####"), "", "[Back to contents](#contents)", "")
}
writeLines(enc2utf8(L), file.path(SAL, "REPORTE_angel.md"), useBytes = TRUE)
cat(sprintf("Reporte escrito en %s: %d aglomerados\n", file.path(SAL, "REPORTE_angel.md"), r$n))
